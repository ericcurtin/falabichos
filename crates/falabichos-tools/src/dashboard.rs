//! The contributors' content dashboard: renders the linter's findings and a few coverage tables as one
//! static HTML page. It lives **outside the game** (the game stays native-only): plain HTML and CSS,
//! no scripts, no external requests, so the file can be opened from disk or published anywhere.

use crate::{LintReport, lint};
use falabichos_assets::Assets;
use falabichos_content::Severity;
use falabichos_core::Content;
use falabichos_core::i18n::parse_table;
use falabichos_core::model::{ChallengeKind, SpeciesKind};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// Escape text for HTML (element content and double-quoted attributes).
pub fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

fn pct(n: usize, total: usize) -> usize {
    (n * 100).checked_div(total).unwrap_or(100)
}

/// A small bar made of two nested blocks (pure CSS).
fn bar(percent: usize) -> String {
    format!(
        "<div class=\"bar\" role=\"img\" aria-label=\"{percent}%\"><div style=\"width:{}%\"></div></div> {percent}%",
        percent.min(100)
    )
}

fn table(out: &mut String, head: &[&str], rows: &[Vec<String>]) {
    out.push_str("<table><thead><tr>");
    for h in head {
        let _ = write!(out, "<th>{}</th>", esc(h));
    }
    out.push_str("</tr></thead><tbody>");
    for r in rows {
        out.push_str("<tr>");
        for cell in r {
            // cells are already HTML (built with `esc` by the callers)
            let _ = write!(out, "<td>{cell}</td>");
        }
        out.push_str("</tr>");
    }
    out.push_str("</tbody></table>");
}

