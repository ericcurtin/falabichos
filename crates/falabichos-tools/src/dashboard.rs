/// Render the dashboard for `assets`.
pub fn render(assets: &Assets) -> String {
    let rep = lint(assets);
    let loaded = falabichos_content::load(assets);
    render_report(assets, &rep, &loaded.content)
}

/// Render the dashboard from an existing lint report and content (testable without re-linting).
pub fn render_report(assets: &Assets, rep: &LintReport, c: &Content) -> String {
    let (e, w, i) = (
        rep.count(Severity::Error),
        rep.count(Severity::Warning),
        rep.count(Severity::Info),
    );
    let mut o = String::new();
    let _ = write!(
        o,
        "<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\
         <title>Falabichos content dashboard</title><style>{CSS}</style></head><body>\n"
    );
    o.push_str("<h1>Falabichos content dashboard</h1>\n");
    o.push_str(
        "<p>Generated by <code>falabichos-dashboard</code> from the linter and the content files. \
         This page is static (no scripts) and lives outside the game. \
         How to fix things: <code>docs/CONTENT_FORMAT.md</code> and <code>CONTRIBUTING.md</code>.</p>\n",
    );
    let (class, word) = if e > 0 {
        ("error", "failing")
    } else if w > 0 {
        ("warning", "passing with warnings")
    } else {
        ("ok", "passing")
    };
    let _ = writeln!(
        o,
        "<p><span class=\"badge {class}\">lint {word}</span> {e} error(s), {w} warning(s), {i} info</p>"
    );

    // ---- overview
    o.push_str("<h2>Overview</h2>\n");
    let exercises: usize = c.grammar.values().map(|g| g.exercises.len()).sum();
    let lines: usize = c
        .dialogues
        .values()
        .flat_map(|d| d.branches.iter())
        .map(|b| b.lines.len())
        .sum();
    let with_audio = c.vocab.values().filter(|v| c.has_clip(&v.audio_slot())).count();
    let rows = vec![
        vec![
            "Towns / maps".into(),
            format!("{} / {}", c.towns.len(), c.maps.len()),
        ],
        vec!["Bichos".into(), c.species.len().to_string()],
        vec![
            "Verbs with conjugation tables".into(),
            format!(
                "{} ({} drill forms)",
                c.verbs.len(),
                c.conjugation_skills(None).len()
            ),
        ],
        vec!["Vocabulary items".into(), c.vocab.len().to_string()],
        vec![
            "Grammar concepts / exercises".into(),
            format!("{} / {}", c.grammar.len(), exercises),
        ],
        vec![
            "Dialogues / lines".into(),
            format!("{} / {}", c.dialogues.len(), lines),
        ],
        vec![
            "Mestres / trainers / Selos".into(),
            format!(
                "{} / {} / {}",
                c.challenges
                    .values()
                    .filter(|x| x.kind == ChallengeKind::Mestre)
                    .count(),
                c.challenges
                    .values()
                    .filter(|x| x.kind == ChallengeKind::Trainer)
                    .count(),
                c.seals.len()
            ),
        ],
        vec![
            "Recorded pronunciation clips".into(),
            format!(
                "{with_audio} of {} vocabulary items {}",
                c.vocab.len(),
                bar(pct(with_audio, c.vocab.len()))
            ),
        ],
        vec![
            "Flagged <code>needs_native_review</code>".into(),
            rep.review_list.len().to_string(),
        ],
    ];
    table(&mut o, &["What", "How many"], &rows);

    // ---- towns
    o.push_str("<h2>Towns</h2>\n");
    let mut rows = vec![];
    for t in c.towns.values() {
        let maps: Vec<&_> = c
            .maps
            .values()
            .filter(|m| m.town.as_deref() == Some(&t.id))
            .collect();
        let npcs: usize = maps.iter().map(|m| m.npcs.len()).sum();
        let trainers: usize = maps
            .iter()
            .flat_map(|m| m.npcs.iter())
            .filter(|n| n.trainer.is_some())
            .count();
        let mestre: Vec<String> = c
            .challenges
            .values()
            .filter(|ch| ch.kind == ChallengeKind::Mestre)
            .filter(|ch| {
                maps.iter().flat_map(|m| m.npcs.iter()).any(|n| {
                    n.dialogue
                        .as_deref()
                        .is_some_and(|d| dialogue_challenges(c, d, &ch.id))
                })
            })
            .map(|ch| esc(&ch.name))
            .collect();
        rows.push(vec![
            format!("<strong>{}</strong><br>{}", esc(&t.name), esc(&t.inspired_by)),
            maps.len().to_string(),
            npcs.to_string(),
            trainers.to_string(),
            if mestre.is_empty() {
                "-".into()
            } else {
                mestre.join(", ")
            },
        ]);
    }
    table(&mut o, &["Town", "Maps", "NPCs", "Trainers", "Mestre"], &rows);

    // ---- vocabulary coverage
    o.push_str("<h2>Vocabulary by category</h2>\n");
    let mut cats: BTreeMap<&str, Vec<&falabichos_core::model::VocabItem>> = BTreeMap::new();
    for v in c.vocab.values() {
        cats.entry(v.category.as_str()).or_default().push(v);
    }
    let mut rows = vec![];
    for (cat, items) in &cats {
        let n = items.len();
        let ipa = items.iter().filter(|v| v.ipa.is_some()).count();
        let ex = items.iter().filter(|v| v.example.is_some()).count();
        let au = items.iter().filter(|v| c.has_clip(&v.audio_slot())).count();
        let rv = items.iter().filter(|v| v.needs_native_review).count();
        rows.push(vec![
            format!("<code>{}</code>", esc(cat)),
            n.to_string(),
            bar(pct(ipa, n)),
            bar(pct(ex, n)),
            bar(pct(au, n)),
            format!("{rv} of {n}"),
        ]);
    }
    table(
        &mut o,
        &[
            "Category",
            "Items",
            "IPA",
            "Example sentence",
            "Recording",
            "Needs review",
        ],
        &rows,
    );

    // ---- grammar
    o.push_str("<h2>Grammar concepts</h2>\n");
    let mut taught_by: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for s in c.species.values() {
        for g in &s.grammar {
            taught_by.entry(g.as_str()).or_default().push(s.name.as_str());
        }
    }
    let mut rows = vec![];
    for g in c.grammar.values() {
        let mut kinds: BTreeMap<String, usize> = BTreeMap::new();
        for ex in &g.exercises {
            *kinds.entry(format!("{:?}", ex.kind)).or_default() += 1;
        }
        let kinds: Vec<String> = kinds.iter().map(|(k, n)| format!("{n} {}", esc(k))).collect();
        let explained = g.exercises.iter().filter(|x| x.explanation.is_some()).count();
        rows.push(vec![
            format!("<code>{}</code><br>{}", esc(&g.id), esc(&g.title)),
            g.exercises.len().to_string(),
            kinds.join(", "),
            bar(pct(explained, g.exercises.len())),
            taught_by
                .get(g.id.as_str())
                .map(|v| esc(&v.join(", ")))
                .unwrap_or_else(|| "<em>no Bicho teaches it</em>".into()),
            if g.needs_native_review {
                "yes".into()
            } else {
                "no".into()
            },
        ]);
    }
    table(
        &mut o,
        &[
            "Concept",
            "Exercises",
            "Kinds",
            "With explanation",
            "Taught by",
            "Needs review",
        ],
        &rows,
    );

    // ---- verbs
    o.push_str("<h2>Verb tables</h2>\n");
    let mut rows = vec![];
    for v in c.verbs.values() {
        rows.push(vec![
            format!("<code>{}</code>", esc(&v.id)),
            esc(&v.en),
            esc(&v.group),
            esc(&v.perfeito.join(" ")),
            if v.needs_native_review {
                "yes".into()
            } else {
                "no".into()
            },
        ]);
    }
    table(
        &mut o,
        &["Verb", "Meaning", "Group", "Pretérito perfeito", "Needs review"],
        &rows,
    );

    // ---- bichos
    o.push_str("<h2>Bichos</h2>\n");
    let mut by_dex: Vec<&falabichos_core::model::Species> = c.species.values().collect();
    by_dex.sort_by_key(|s| s.dex_no);
    let mut rows = vec![];
    for s in by_dex {
        let found: Vec<String> = c
            .maps
            .values()
            .filter(|m| m.encounters.iter().any(|en| en.species == s.id))
            .map(|m| esc(&m.name))
            .collect();
        rows.push(vec![
            format!("#{}", s.dex_no),
            format!("<strong>{}</strong> (<code>{}</code>)", esc(&s.name), esc(&s.id)),
            match s.kind {
                SpeciesKind::Vocab => format!("{} words", s.vocab.len()),
                SpeciesKind::Grammar => format!("{} concepts", s.grammar.len()),
            },
            esc(&s.theme),
            if found.is_empty() {
                "<em>nowhere</em>".into()
            } else {
                found.join(", ")
            },
            if s.needs_native_review {
                "yes".into()
            } else {
                "no".into()
            },
        ]);
    }
    table(
        &mut o,
        &["Dex", "Bicho", "Teaches", "Theme", "Found in", "Needs review"],
        &rows,
    );

    // ---- UI languages
    o.push_str("<h2>Interface languages</h2>\n");
    let en = assets
        .text("i18n/en/ui.lang")
        .map(parse_table)
        .unwrap_or_default();
    let langs: BTreeSet<String> = assets
        .list("i18n/")
        .filter_map(|p| p.strip_prefix("i18n/")?.strip_suffix("/ui.lang"))
        .map(String::from)
        .collect();
    let mut rows = vec![];
    for l in &langs {
        let tbl = assets
            .text(&format!("i18n/{l}/ui.lang"))
            .map(parse_table)
            .unwrap_or_default();
        let done = en.keys().filter(|k| tbl.contains_key(*k)).count();
        let issues = rep
            .diagnostics
            .iter()
            .filter(|d| d.location == format!("i18n/{l}/ui.lang"))
            .count();
        rows.push(vec![
            format!(
                "<code>{}</code> {}",
                esc(l),
                esc(tbl.get("lang.name").map(String::as_str).unwrap_or(""))
            ),
            format!("{done} of {}", en.len()),
            bar(pct(done, en.len())),
            issues.to_string(),
        ]);
    }
    table(
        &mut o,
        &["Language", "Keys translated", "", "Lint findings"],
        &rows,
    );

    // ---- diagnostics
    o.push_str("<h2>Lint findings</h2>\n");
    if rep.diagnostics.is_empty() {
        o.push_str("<p>Nothing to report.</p>\n");
    } else {
        o.push_str("<table><thead><tr><th>Severity</th><th>Where</th><th>What</th></tr></thead><tbody>");
        for d in &rep.diagnostics {
            let (class, label) = match d.severity {
                Severity::Error => ("sev-error", "error"),
                Severity::Warning => ("sev-warning", "warning"),
                Severity::Info => ("sev-info", "info"),
            };
            let _ = write!(
                o,
                "<tr class=\"{class}\"><td>{label}</td><td><code>{}</code></td><td>{}</td></tr>",
                esc(&d.location),
                esc(&d.message)
            );
        }
        o.push_str("</tbody></table>\n");
    }

    // ---- review queue
    o.push_str("<h2>Waiting for a native speaker</h2>\n");
    o.push_str(
        "<p>Items flagged <code>needs_native_review: true</code>. Fix them and clear the flag only if you are confident \
         (see Track 1 in <code>CONTRIBUTING.md</code>).</p>\n",
    );
    let mut by_kind: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (k, id) in &rep.review_list {
        by_kind.entry(k.as_str()).or_default().push(id.as_str());
    }
    for (k, ids) in &by_kind {
        let _ = write!(
            o,
            "<details><summary><strong>{}</strong>: {}</summary><p>",
            esc(k),
            ids.len()
        );
        let list: Vec<String> = ids.iter().map(|i| format!("<code>{}</code>", esc(i))).collect();
        o.push_str(&list.join(" "));
        o.push_str("</p></details>\n");
    }
    if by_kind.is_empty() {
        o.push_str("<p>Everything has been reviewed.</p>\n");
    }

    // ---- audio
    o.push_str("<h2>Recordings still needed</h2>\n");
    let _ = write!(
        o,
        "<details><summary>{} vocabulary item(s) without a clip (spec: <code>docs/AUDIO_GUIDE.md</code>)</summary><p>",
        rep.missing_audio.len()
    );
    let list: Vec<String> = rep
        .missing_audio
        .iter()
        .map(|i| format!("<code>{}</code>", esc(i)))
        .collect();
    o.push_str(&list.join(" "));
    o.push_str("</p></details>\n");

    let _ = writeln!(
        o,
        "<footer>falabichos-dashboard {} - Apache-2.0</footer></body></html>",
        env!("CARGO_PKG_VERSION")
    );
    o
}

/// Does dialogue `d` (any branch) start the challenge `challenge`?
fn dialogue_challenges(c: &Content, dialogue: &str, challenge: &str) -> bool {
    c.dialogues.get(dialogue).is_some_and(|dlg| {
        dlg.branches.iter().any(|b| {
            b.then
                .iter()
                .any(|a| matches!(a, falabichos_core::model::Action::Challenge(id) if id == challenge))
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escaping() {
        assert_eq!(
            esc("<a href=\"x\">Tom & 'Jerry'</a>"),
            "&lt;a href=&quot;x&quot;&gt;Tom &amp; &#39;Jerry&#39;&lt;/a&gt;"
        );
    }

    #[test]
    fn dashboard_covers_the_shipped_content_and_has_no_scripts() {
        let html = render(&Assets::embedded());
        assert!(html.starts_with("<!DOCTYPE html>"));
        for needle in [
            "Falabichos content dashboard",
            "lint passing",
            "Ribeira Dourada",
            "Mestre Duarte",
            "Vocabulary by category",
            "<code>directions</code>",
            "ter_haver",
            "Rabelo",
            "Verb tables",
            "falámos",
            "Interface languages",
            "Français",
            "Waiting for a native speaker",
            "Recordings still needed",
        ] {
            assert!(html.contains(needle), "dashboard lacks {needle:?}");
        }
        let lower = html.to_lowercase();
        assert!(
            !lower.contains("<script"),
            "the dashboard must not need JavaScript"
        );
        assert!(
            !lower.contains("http://") && !lower.contains("https://"),
            "no external requests"
        );
        // well-formed enough: every opened table is closed
        assert_eq!(html.matches("<table>").count(), html.matches("</table>").count());
    }

    #[test]
    fn findings_are_shown_and_html_in_content_cannot_inject_markup() {
        let mut assets = Assets::embedded();
        // a vocab file with a broken entry (no English) and markup in its text
        assets.insert(
            "content/vocab/zz_test.ron",
            br#"[(id: "evil", pt: "<script>alert(1)</script>", en: [], category: "x<b>y", needs_native_review: true)]"#
                .to_vec(),
        );
        let html = render(&assets);
        assert!(html.contains("lint failing"));
        assert!(html.contains("vocab:evil"));
        assert!(html.contains("&lt;b&gt;"), "category is escaped");
        assert!(!html.contains("<script>alert"), "content is escaped");
        assert!(!html.to_lowercase().contains("<script"));
    }

    #[test]
    fn the_page_is_deterministic() {
        let a = Assets::embedded();
        assert_eq!(render(&a), render(&a));
    }
}
